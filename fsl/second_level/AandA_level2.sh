# -----------------------------------------------------------------------------------------------------------------------------------
#
# -----------------------------------------------------------------------------------------------------------------------------------
##
###
#### Start loop across subjects: 
###
##
# -----------------------------------------------------------------------------------------------------------------------------------
for NUMSUBS in $*; do
SUBJ=$NUMSUBS
echo -e "\nThis script is currently working on......................$SUBJ\n"

# -----------------------------------------------------------------------------------------------------------------------------------
##
###
#### Go ahead and give the PARENT folder for the STUDY, then set as CWD:
###
##
# -----------------------------------------------------------------------------------------------------------------------------------
FSLDATADIR=/path/to/data/AandA
cd ${FSLDATADIR}

# -----------------------------------------------------------------------------------------------------------------------------------
##
###
#### Set directory for subject first level data:
###
##
# -----------------------------------------------------------------------------------------------------------------------------------
SUBJDIR=${FSLDATADIR}/FSLoutput/Level1/${SUBJ}

# -----------------------------------------------------------------------------------------------------------------------------------
##
###
#### Set a place for second level output:
###
##
# -----------------------------------------------------------------------------------------------------------------------------------
L2OUT=${FSLDATADIR}/FSLoutput/Level2/$SUBJ

# -----------------------------------------------------------------------------------------------------------------------------------
##
###
#### Set location of *.fsf files that are created below, then make the directory:
###
##
# -----------------------------------------------------------------------------------------------------------------------------------
FEATDIR=${FSLDATADIR}/FSLoutput/Level2/FEATdir/

if [ ! -d ${FEATDIR} ]; then 
mkdir -p ${FEATDIR}
fi

# -----------------------------------------------------------------------------------------------------------------------------------
##
###
#### Create individual *.fsf files, dumping them into the 2nd level: 
###
##
# -----------------------------------------------------------------------------------------------------------------------------------
echo -e "Output of this analysis can be found in $L2OUT.gfeat\n"

    for i in 'AandA-Level2.fsf'; do
    sed -e 's@L2OUT@'$L2OUT'@g' \
	-e 's@SUBJDIR@'$SUBJDIR'@g' <$i> ${FEATDIR}/FEAT_${SUBJ}.fsf

# -----------------------------------------------------------------------------------------------------------------------------------
##
###
#### Close loop for within-file replacement:
###
##
# -----------------------------------------------------------------------------------------------------------------------------------
    done

# -----------------------------------------------------------------------------------------------------------------------------------
##
###
#### Execute the FSL analysis/es by calling the newly created FEAT*.fsf file: 
###
##
# -----------------------------------------------------------------------------------------------------------------------------------
feat ${FEATDIR}/FEAT_${SUBJ}.fsf

# -----------------------------------------------------------------------------------------------------------------------------------
##
###
#### End subject loop: 
###
##
# -----------------------------------------------------------------------------------------------------------------------------------
done

# -----------------------------------------------------------------------------------------------------------------------------------
##
###
#### End of file: 
###
##
# -----------------------------------------------------------------------------------------------------------------------------------
